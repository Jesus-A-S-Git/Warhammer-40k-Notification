// Army list pricer: paste an army list, get the boxes to buy and the cheapest
// delivered plan. Browser-safe (shared by POST /api/prices/army and the static site).
//
// Understands:
//  * the official Warhammer 40,000 app export
//      "Intercessor Squad (80 points)" + "• 4x Intercessor" / "◦ 1x Bolt rifle" lines
//  * BattleScribe / New Recruit text exports
//      "Intercessor Squad [160pts]:" + ". 9x Intercessor: 9x Bolt rifle" lines,
//      "++ Army Roster (Imperium - Space Marines) [2,000pts] ++", "+ Battleline +"
//  * New Recruit "WTC compact" lines
//      "Char1: 1x Overlord (85 pts): Warlord, ..." / "10x Necron Warriors (90 pts): ..."
//  * plain lines: "10x Intercessor Squad", "3 Hellblasters", "Necron Warriors (20)",
//    "Necron Warriors x20", "2 x Redemptor Dreadnought"
//
// A leading number counts MODELS ("10x Intercessor Squad" = ten Intercessors);
// for single-model datasheets it is the number of units, and a number below
// the unit's minimum size is read as that many units ("3 Hellblasters" = three
// squads of five). Lines say how they were read in `note`.
import { ALL_UNITS } from '../combat/data/catalog.js';
import { rankUnits } from '../combat/unitSearch.js';
import { normalize } from '../search/fuzzy.js';
import { CATALOG, slug } from './catalog.js';
import { planCart } from './overview.js';

export const MAX_LIST_CHARS = 20_000;
export const MAX_LINES = 400;

const POINTS_RE = /[([]\s*\+?\s*[\d,]+\s*(?:pts?|points?)\s*[)\]]/gi;
const BULLET_RE = /^\s*([•◦▪▫‣⁃●○∙·*\-–+]|\.{1,3})\s*/u;
const SKIP_RE = /^(exported with|created with|generated by|army roster|battle size|detachment|detachment rule|total|faction|sub-?faction|chapter|strike force|incursion|onslaught|combat patrol \(|warlord|points?|game type|show|enhancements?:|\+\+|#|\/\/)/i;
const SECTION_WORDS = /^(characters?|battleline|dedicated transports?|other datasheets|allied units|fortifications?|epic heroes?|hq|troops|elites|fast attack|heavy support|flyers?|lords of war|transports?|units?|configuration|rules|selections?)$/i;

// Combat-catalogue faction names, longest first (so "Chaos Space Marines" wins over "Space Marines").
const UNIT_FACTIONS = [...new Set(ALL_UNITS.map((u) => u.faction))].sort((a, b) => b.length - a.length);
const SM_CHAPTERS = new Set(['Blood Angels', 'Dark Angels', 'Space Wolves', 'Black Templars', 'Deathwatch',
  'Ultramarines', 'Imperial Fists', 'Iron Hands', 'Raven Guard', 'Salamanders', 'White Scars']);

/** Factions named in the list's header lines ("Space Marines", "Xenos - Necrons", "(Imperium - Space Marines)"). */
export function detectFactions(lines) {
  const found = new Set();
  for (const raw of lines.slice(0, 60)) {
    const line = raw.trim();
    if (!line || BULLET_RE.test(raw) && !/^\s*\+/.test(raw)) continue;
    const n = ` ${normalize(line)} `;
    const headerish = /^(\+|faction|army|\+\+)/i.test(line) || !/\d/.test(line) || /roster|faction|keyword/i.test(line);
    if (!headerish) continue;
    for (const f of UNIT_FACTIONS) {
      const k = normalize(f);
      if (!n.includes(` ${k} `)) continue;
      // A bare line that only names a faction, or an explicit roster/faction header.
      if (normalize(line) === k || /roster|faction|keyword|\+/i.test(line) || normalize(line).endsWith(k)) {
        found.add(f);
        break;
      }
    }
  }
  if ([...found].some((f) => SM_CHAPTERS.has(f))) found.add('Space Marines');
  if (found.has('Space Marines')) for (const c of ['Ultramarines', 'Imperial Fists', 'Iron Hands', 'Raven Guard', 'Salamanders', 'White Scars']) found.add(c);
  return [...found];
}

/** Name, explicit model count and points from a unit line. */
export function parseHead(text) {
  let t = String(text).replace(/\s+/g, ' ').trim();
  t = t.replace(/^(char|unit|ally|allied|epic hero|enh)\s*\d*\s*:\s*/i, '');
  t = t.replace(BULLET_RE, '');
  let qty = null;
  let m = t.match(/^(\d{1,3})\s*[x×]\s*(?=\S)/i) ?? t.match(/^(\d{1,3})\s+(?=[a-z])/i);
  if (m) { qty = Number(m[1]); t = t.slice(m[0].length); }
  const pts = [...t.matchAll(POINTS_RE)].map((x) => Number(x[0].replace(/[^\d]/g, '')));
  t = t.replace(POINTS_RE, ' ');
  // "Name: wargear, wargear" (BattleScribe / WTC compact)
  const colon = t.indexOf(':');
  if (colon > 0) t = t.slice(0, colon);
  t = t.replace(/\[(legends?|warlord)\]/gi, ' ').replace(/\((legends?|warlord)\)/gi, ' ');
  m = t.match(/\(\s*(\d{1,3})\s*(?:models?|x|miniatures?)?\s*\)\s*$/i)
    ?? t.match(/\[\s*(\d{1,3})\s*(?:models?)?\s*\]\s*$/i)
    ?? t.match(/\s[x×]\s*(\d{1,3})\s*$/i)
    ?? t.match(/\s[-–:]\s*(\d{1,3})\s*$/)
    ?? t.match(/\s(\d{1,3})\s*models?\s*$/i);
  if (m) { if (qty == null) qty = Number(m[1]); t = t.slice(0, m.index); }
  t = t.replace(/\s[-–]\s*warlord\s*$/i, '').replace(/[\s,;:.\-–]+$/, '').replace(/^[\s,;:.\-–]+/, '').trim();
  return { name: t, qty, points: pts.length ? pts[0] : null };
}

const levelOf = (raw) => {
  const lead = raw.match(/^\s*/)[0].replace(/\t/g, '    ').length;
  const b = raw.match(BULLET_RE)?.[1] ?? '';
  const dots = /^\.+$/.test(b) ? b.length : 0;
  const deep = /[◦▫○]/u.test(b) ? 2 : 0;
  return Math.max(dots, deep, b ? 1 : 0, lead >= 2 ? 1 + Math.floor((lead - 2) / 3) : 0);
};

/**
 * Split a pasted list into unit entries.
 * @returns {{format:string, factions:string[], entries:{raw:string, name:string, qty:number|null,
 *            subModels:number|null, points:number|null}[], ignored:string[]}}
 */
export function parseArmyList(text) {
  const src = String(text ?? '').slice(0, MAX_LIST_CHARS).replace(/\r\n?/g, '\n');
  const lines = src.split('\n').slice(0, MAX_LINES);
  const structured = lines.some((l) => { POINTS_RE.lastIndex = 0; return POINTS_RE.test(l); });
  POINTS_RE.lastIndex = 0;
  const format = !structured ? 'plain'
    : lines.some((l) => /^\s*(char|unit)\d*\s*:/i.test(l) || /^\s*\+\s*(faction keyword|detachment|total army points)/i.test(l)) ? 'newrecruit-wtc'
      : lines.some((l) => /^\s*\+\+/.test(l) || /^\s*\.\s+\S/.test(l)) ? 'battlescribe'
        : lines.some((l) => /[•◦]/u.test(l)) ? 'warhammer-app' : 'points-list';
  const factions = detectFactions(lines);
  const entries = []; const ignored = [];
  let cur = null;
  const subs = []; // sub-lines of the current unit: {level, qty, hasColon}
  const close = () => {
    if (!cur) return;
    // Model lines: level-1 sub-lines that have deeper lines under them, or a
    // BattleScribe ". 9x Intercessor: wargear" selection.
    let n = 0; let any = false;
    subs.forEach((s, i) => {
      if (s.level !== 1) return;
      const child = subs[i + 1] && subs[i + 1].level > 1;
      if (child || (s.dot && s.hasColon)) { n += s.qty ?? 1; any = true; }
    });
    cur.subModels = any ? n : null;
    entries.push(cur); cur = null; subs.length = 0;
  };
  for (const raw of lines) {
    const line = raw.trim();
    if (!line) continue;
    const plainText = line.replace(BULLET_RE, '').trim();
    POINTS_RE.lastIndex = 0;
    const hasPts = POINTS_RE.test(line);
    POINTS_RE.lastIndex = 0;
    const isSub = BULLET_RE.test(raw) && !/^\s*\+/.test(raw) && !/^\s*(char|unit)\d*\s*:/i.test(raw);
    if (/^\s*\+/.test(raw) || SECTION_WORDS.test(plainText.replace(/[^a-z ]/gi, '').trim())
      || (SKIP_RE.test(plainText) && !hasPts) || /^(strike force|incursion|onslaught)\b/i.test(plainText)
      || /^exported with/i.test(plainText)) {
      if (!/^\s*\+/.test(raw)) close();
      else close();
      continue;
    }
    if (structured) {
      if (isSub && cur && !hasPts) {
        const m = plainText.match(/^(\d{1,3})\s*[x×]\s*/i);
        subs.push({ level: Math.max(1, levelOf(raw)), qty: m ? Number(m[1]) : null,
          hasColon: plainText.includes(':'), dot: /^\s*\.\s/.test(raw) });
        continue;
      }
      if (isSub && !hasPts) continue;
      if (!hasPts) { close(); ignored.push(line); continue; }
      close();
      const h = parseHead(line);
      cur = { raw: line, ...h, subModels: null };
      continue;
    }
    // Plain list: every line is a unit.
    const h = parseHead(plainText);
    if (h.name) entries.push({ raw: line, ...h, subModels: null });
  }
  close();
  return { format, factions, entries, ignored };
}

// ---- unit and kit resolution -----------------------------------------------------------

const unitCache = new Map();
/** Datasheet for a name, preferring the list's factions. */
export function resolveArmyUnit(name, factions = []) {
  const key = `${factions.join(',')}|${normalize(name)}`;
  if (unitCache.has(key)) return unitCache.get(key);
  const pick = (units) => {
    const [top, next] = rankUnits(units, name);
    if (!top || top.score < 0.85 || (!top.exact && top.coverage < 0.5)) return null;
    if (next && next.exact === top.exact && next.score === top.score && next.coverage === top.coverage) return null;
    return top.unit;
  };
  let u = null;
  if (factions.length) {
    const fs = new Set(factions);
    u = pick(ALL_UNITS.filter((x) => fs.has(x.faction)));
  }
  u ??= pick(ALL_UNITS);
  if (unitCache.size > 2000) unitCache.clear();
  unitCache.set(key, u);
  return u;
}

// unitId -> kits that build it (unit kits first; single-datasheet kits first).
const KITS_BY_UNIT = new Map();
for (const e of CATALOG) {
  for (const id of e.units ?? []) {
    if (!KITS_BY_UNIT.has(id)) KITS_BY_UNIT.set(id, []);
    KITS_BY_UNIT.get(id).push(e);
  }
}
for (const list of KITS_BY_UNIT.values()) {
  list.sort((a, b) => (a.category === 'kit' ? 0 : 1) - (b.category === 'kit' ? 0 : 1)
    || (a.units.length - b.units.length) || ((a.USD ?? Infinity) - (b.USD ?? Infinity)) || a.id.localeCompare(b.id));
}
/** The boxed kit to buy for a datasheet id, or null. */
export function kitForUnit(unitId) {
  return KITS_BY_UNIT.get(unitId)?.[0] ?? null;
}

const clampInt = (v, lo, hi) => Math.max(lo, Math.min(hi, Math.floor(Number(v) || 0)));

/**
 * Lines, unmatched entries and the boxes to buy (before planning).
 * @param {string} list
 * @param {Record<string, number>} [owned]  productId -> boxes already owned
 */
export function armyItems(list, owned = {}) {
  const parsed = parseArmyList(list);
  const lines = []; const unmatched = [];
  const need = new Map(); // productId -> {models, perBox, unitBoxes}
  for (const e of parsed.entries) {
    const unit = e.name ? resolveArmyUnit(e.name, parsed.factions) : null;
    if (!unit) {
      // "My Army (2000 points)" / "Strike Force (2000 points)": a list title, not a unit.
      if (e.qty == null && e.points != null && e.points >= 500) continue;
      unmatched.push(e.raw);
      continue;
    }
    const min = unit.models?.min ?? 1; const max = unit.models?.max ?? min;
    const notes = [];
    let models; let units = 1;
    const n = e.qty ?? e.subModels;
    if (n == null) {
      models = unit.models?.default ?? min;
      if (max > 1) notes.push(`model count not given; assumed ${models}`);
    } else if (max <= 1) {
      models = n; units = n;
    } else if (n < min) {
      units = n; models = n * min;
      notes.push(`read as ${n} unit${n === 1 ? '' : 's'} of ${min}`);
    } else models = n;
    const kit = kitForUnit(unit.id);
    const perBox = kit?.models ?? null;
    let boxes = 0;
    if (kit) {
      boxes = perBox ? Math.ceil(models / perBox) : units;
      if (!perBox) notes.push('box contents unknown; assumed one box per unit');
      const cur = need.get(kit.id) ?? { models: 0, perBox, unitBoxes: 0 };
      cur.models += models; cur.unitBoxes += boxes;
      need.set(kit.id, cur);
    } else notes.push('no boxed kit for this datasheet in our catalogue yet');
    lines.push({ raw: e.raw, qty: models, unitName: unit.name, unitId: unit.id, productId: kit?.id ?? null,
      boxes, modelsPerBox: perBox, note: notes.length ? notes.join('; ') : null, points: e.points ?? null });
  }
  const items = [];
  const ownedUsed = {};
  for (const [productId, v] of need) {
    // Boxes are pooled per kit: two 5-model squads come from one 10-model box.
    const total = v.perBox ? Math.ceil(v.models / v.perBox) : v.unitBoxes;
    const have = clampInt(owned?.[productId], 0, 999);
    const qty = Math.max(0, total - have);
    if (have) ownedUsed[productId] = Math.min(have, total);
    if (qty > 0) items.push({ productId, qty });
  }
  return { format: parsed.format, factions: parsed.factions, lines, unmatched, items, owned: ownedUsed };
}

/** Validate the request body; returns an error message or null. */
export function armyRequestError(body) {
  const list = body?.list;
  if (typeof list !== 'string' || !list.trim()) return '"list" must be the army list as text';
  if (list.length > MAX_LIST_CHARS) return `"list" must be at most ${MAX_LIST_CHARS} characters`;
  const owned = body?.owned;
  if (owned != null && (typeof owned !== 'object' || Array.isArray(owned))) return '"owned" must be an object {productId: boxes}';
  return null;
}

/**
 * POST /api/prices/army result.
 * @param {object} ov  overview (overview.js)
 */
export function armyPayload(ov, list, owned = {}, { overrides } = {}) {
  const a = armyItems(list, owned);
  const byId = new Map((ov?.products ?? []).map((p) => [p.id, p]));
  const plan = planCart(ov, a.items.slice(0, 40).map((i) => ({ id: i.productId, qty: i.qty })), { overrides });
  let rrp = 0; let rrpAny = false; let savings = 0; let savAny = false;
  const unitPrice = new Map();
  for (const g of plan.plan) for (const it of g.items) unitPrice.set(it.id, it.unitPrice);
  for (const it of a.items) {
    const r = byId.get(it.productId)?.rrp;
    if (r != null) { rrp += r * it.qty; rrpAny = true; }
    if (r != null && unitPrice.has(it.productId)) { savings += (r - unitPrice.get(it.productId)) * it.qty; savAny = true; }
  }
  const r2 = (n) => Math.round(n * 100) / 100;
  return {
    format: a.format, factions: a.factions,
    lines: a.lines, unmatched: a.unmatched, items: a.items, owned: a.owned,
    plan,
    totals: {
      rrp: rrpAny ? r2(rrp) : null,
      best: plan.plan.length ? plan.goods : null,
      delivered: plan.plan.length ? plan.total : null,
      savings: savAny ? r2(savings) : null,
    },
  };
}

