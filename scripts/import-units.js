// Generate src/combat/data/units.generated.js from the BSData wh40k-10e
// BattleScribe catalogues (https://github.com/BSData/wh40k-10e).
//
// Usage:
//   node scripts/import-units.js                 download the catalogues (pinned ref) via politeFetch
//   node scripts/import-units.js --ref main      download a different git ref
//   node scripts/import-units.js --from <dir>    read .cat/.gst files from a local checkout (no network)
//   node scripts/import-units.js --dry-run       print the report only
//
// Downloads go through politeFetch (robots.txt, caching, backoff) with a small
// budget: 6 requests/minute, one at a time. About 50 files, run by hand when
// the data needs refreshing; the output is committed so the server and the
// static build never fetch datasheets at runtime.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { politeFetch, setHostLimit } from '../src/shared/httpClient.js';
import { parseXml, convertBsdata } from '../src/combat/import/bsdata.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'src/combat/data/units.generated.js');

export const BSDATA_HOST = 'raw.githubusercontent.com';
export const BSDATA_REPO = 'BSData/wh40k-10e';
export const BSDATA_REF = '6056155b5e2100e4f656707b24ac080d7c46d323'; // main @ 2026-08-05
export const BSDATA_LIMIT = { requestsPerMinute: 6, burst: 1, maxConcurrent: 1 };

// The repository's catalogue files (no directory listing on raw.githubusercontent.com).
