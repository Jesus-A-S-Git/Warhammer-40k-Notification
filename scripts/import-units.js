const arg = (name) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : undefined; };

async function loadLocal(dir) {
  const names = (await readdir(dir)).filter((f) => /\.(cat|gst)$/.test(f)).sort();
  return Promise.all(names.map(async (file) => ({ file, xml: await readFile(path.join(dir, file), 'utf8') })));
}

export async function download(ref = BSDATA_REF, files = BSDATA_FILES, { hostLimit = BSDATA_LIMIT } = {}) {
  setHostLimit(BSDATA_HOST, hostLimit); // hostLimit override: tests only
  const out = [];
  for (const file of files) { // sequential: one request at a time
    const url = `https://${BSDATA_HOST}/${BSDATA_REPO}/${encodeURIComponent(ref)}/${encodeURIComponent(file)}`;
    process.stderr.write(`fetch ${file}\n`);
    const xml = await politeFetch(url, { as: 'text', ttlMs: 3600_000, timeoutMs: 90_000, maxRetries: 2,
      headers: { Accept: 'application/xml, text/plain' } });
    out.push({ file, xml });
  }
  return out;
}

async function main() {
  const from = arg('--from');
  const ref = arg('--ref') || BSDATA_REF;
  const raw = from ? await loadLocal(path.resolve(from)) : await download(ref);
  const files = raw.map(({ file, xml }) => ({ file, doc: parseXml(xml) }));
  const { units, report } = convertBsdata(files);

  const summary = {
    files: files.length, entries: report.entries, converted: report.converted, hidden: report.hidden,
    skipped: report.skipped.length, weaponsDropped: report.weaponsDropped, byFaction: report.byFaction,
  };
  console.error(JSON.stringify(summary, null, 2));
  if (process.argv.includes('--verbose')) for (const s of report.skipped) console.error(`skip ${s.faction} / ${s.name}: ${s.reason}`);
  if (process.argv.includes('--dry-run')) return;

  const header = `// GENERATED by scripts/import-units.js. Do not edit by hand: re-run the importer.
//
// Source: BSData wh40k-10e (https://github.com/${BSDATA_REPO}) @ ${from ? 'local checkout' : ref},
// community-maintained BattleScribe data. Not affiliated with or endorsed by Games Workshop.
// Warhammer 40,000 and all associated names are trademarks of Games Workshop Ltd.
// Profiles may lag behind codexes, FAQs and balance dataslates: verify against
// the official datasheets before relying on them.
//
// ${units.length} datasheets. Hand-curated entries in units.js win over these (see catalog.js).
`;
  const body = `export const GENERATED_META = ${JSON.stringify({
    source: 'BSData wh40k-10e', url: `https://github.com/${BSDATA_REPO}`, ref: from ? 'local' : ref,
    generatedAt: new Date().toISOString().slice(0, 10), units: units.length,
  })};\n\nexport const GENERATED_UNITS = [\n${units.map((u) => JSON.stringify(u)).join(',\n')}\n];\n`;
  await writeFile(OUT, header + body);
  console.error(`wrote ${path.relative(root, OUT)} (${units.length} units)`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main().catch((err) => { console.error(err); process.exitCode = 1; });
